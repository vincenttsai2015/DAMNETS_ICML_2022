#!/bin/bash
# 掃出哪些組合可以算 MMD / KS，並送出評估。
#
#   bash check_eval.sh                 列出狀態
#   bash check_eval.sh --submit        送出可以算的
#   ONLY=wiki_vote bash check_eval.sh
#   MMD_MAX_SEQS=36 bash check_eval.sh --submit
#
# temporal_baseline_evaluator.py 直接開四個模型的檔，缺任何一個就中斷，
# 所以只有四個模型都齊的組合能算。
#
# MMD 是 O(序列數²)。各組的序列數差很多（wiki-vote 38 條、superuser 680 條，
# 配對數差 320 倍），不設上限的話 superuser 跑不完。MMD_MAX_SEQS 對所有組合
# 要用同一個值，否則數字不可比。

set -eo pipefail
cd "$(dirname "$0")"

RESULT_ROOT=../test_and_generated_graphs
# 要納入比較的模型。TagGen 對每一條序列各自訓練一個 transformer，
# superuser 一組要 24 小時以上，佔了整批九成以上的時間，因此移出預設。
# 要加回來：BASELINE_MODELS="DAMNET AGE TagGen DYMOND"
MODELS=${BASELINE_MODELS:-"DAMNET AGE DYMOND"}
SEED_TAG=${SEED_TAG:-0}
LIMIT=${LIMIT:-20}
SUBMIT=0
[ "$1" = "--submit" ] && SUBMIT=1

RUNNING=""
N_RUNNING=$( { squeue -u "$USER" -h 2>/dev/null || true; } | wc -l )
if [ "$N_RUNNING" -gt 0 ]; then
    echo "queue 裡有 ${N_RUNNING} 個 job。"
    for j in $(squeue -u "$USER" -h -o "%i" 2>/dev/null); do
        cmd=$(scontrol show job "$j" 2>/dev/null | grep -o 'Command=.*' | head -1)
        cmd=${cmd#Command=}
        set -- $cmd
        case "$1" in
            *run_eval.sh) [ -n "$2" ] && RUNNING="${RUNNING} ${2}_${3}" ;;
        esac
    done
fi

N_DONE=0; N_READY=0; N_WAIT=0; N_RUN=0
READY=""

DIRS=$(find "$RESULT_ROOT" -maxdepth 1 -type d -name "macro_*_${SEED_TAG}" 2>/dev/null | sort)
[ -n "$DIRS" ] || { echo "[ERROR] 找不到 ${RESULT_ROOT}/macro_*_${SEED_TAG}"; exit 1; }

mkdir -p logs
for d in $DIRS; do
    key=${d##*/}
    if [ -n "$ONLY" ] && [ "${key#*$ONLY}" = "$key" ]; then continue; fi

    seed=${key##*_}
    ds=${key%_*}

    miss=""
    for m in $MODELS; do
        [ -f "$d/$m/sampled_ts.pkl" ] || miss="$miss $m"
        [ -f "$d/$m/test_graphs.pkl" ] || miss="$miss ${m}(來源)"
    done

    if [ -s "logs/eval_${key}.txt" ] \
       && grep -q "MMD in data generated by" "logs/eval_${key}.txt" 2>/dev/null; then
        N_DONE=$((N_DONE + 1))
        continue
    fi

    case " $RUNNING " in
        *" $key "*) N_RUN=$((N_RUN + 1)); printf '%-52s 評估中\n' "$key"; continue ;;
    esac

    if [ -n "$miss" ]; then
        N_WAIT=$((N_WAIT + 1))
        printf '%-52s 還不能算，缺:%s\n' "$key" "$miss"
    else
        N_READY=$((N_READY + 1))
        printf '%-52s 可以算\n' "$key"
        READY="${READY}sbatch --job-name=ev_${key} run_eval.sh ${ds} ${seed}
"
    fi
done

echo
echo "已完成 ${N_DONE} 組，可以算 ${N_READY} 組，等 baseline 補跑 ${N_WAIT} 組，評估中 ${N_RUN} 組"
[ "$N_READY" -eq 0 ] && exit 0

echo
echo "--- 送出指令 ---"
printf '%s' "$READY"

if [ -z "${MMD_MAX_SEQS:-}" ] || [ "${MMD_MAX_SEQS}" = "0" ]; then
    echo
    echo "[注意] 沒有設定 MMD_MAX_SEQS。MMD 是 O(序列數²)，superuser 一組 680 條"
    echo "       是 wiki-vote 38 條的 320 倍計算量，48 小時可能跑不完。"
    echo "       要跨資料集比較的話所有組合要用同一個值，例如："
    echo "         MMD_MAX_SEQS=36 bash check_eval.sh --submit"
fi

if [ "$SUBMIT" = "1" ]; then
    SLOTS=$((LIMIT - N_RUNNING))
    echo
    echo "queue 現有 ${N_RUNNING} 個，上限 ${LIMIT}，這次可送 ${SLOTS} 個（待送 ${N_READY} 個）"
    if [ "$SLOTS" -le 0 ]; then
        echo "沒有名額，等 queue 空出來再執行一次"
        exit 0
    fi

    echo
    echo "--- 送出 ---"
    n=0
    printf '%s' "$READY" | while read -r cmd; do
        [ -n "$cmd" ] || continue
        n=$((n + 1))
        [ "$n" -gt "$SLOTS" ] && break
        # MMD_MAX_SEQS 要傳進 job 環境
        echo "$cmd"
        eval "${cmd/sbatch /sbatch --export=ALL,MMD_MAX_SEQS=${MMD_MAX_SEQS:-0} }"
    done

    if [ "$N_READY" -gt "$SLOTS" ]; then
        echo
        echo "還有 $((N_READY - SLOTS)) 個沒送，等 queue 空出來再執行一次"
    fi
fi
